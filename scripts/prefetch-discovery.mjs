#!/usr/bin/env node
// Prefetch /v1/sitemap-data into _data/discovery.yml. Run before
// `bundle exec jekyll build`. Env: DISCOVERY_API_URL, PREFETCH_TIMEOUT.

import { writeFile, mkdir, access } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT = resolve(ROOT, '_data', 'discovery.yml');

const API_URL =
  process.env.DISCOVERY_API_URL ??
  'https://api.tourcoaster.com/v1/sitemap-data';
const TIMEOUT_MS = Number.parseInt(process.env.PREFETCH_TIMEOUT ?? '8000', 10);

const yamlEscape = (v) => {
  if (v == null) return '~';
  const s = String(v);
  if (/^[A-Za-z0-9_./:-]+$/.test(s) && s.length < 200) return s;
  return JSON.stringify(s);
};

const renderYaml = (payload) => {
  const lines = [
    '# AUTO-GENERATED by scripts/prefetch-discovery.mjs — do not edit by hand.',
    `generated_at: ${yamlEscape(payload.generated_at)}`,
    `source: ${yamlEscape(API_URL)}`,
    'tours:',
  ];
  for (const t of payload.tours ?? []) {
    lines.push(`  - slug: ${yamlEscape(t.slug)}`);
    lines.push(`    title: ${yamlEscape(t.title)}`);
    lines.push(`    location: ${yamlEscape(t.location)}`);
    lines.push(`    category: ${yamlEscape(t.category)}`);
    lines.push(`    vr_enabled: ${t.vr_enabled ? 'true' : 'false'}`);
    lines.push(`    updated_at: ${yamlEscape(t.updated_at)}`);
  }
  lines.push('guides:');
  for (const g of payload.guides ?? []) {
    lines.push(`  - slug: ${yamlEscape(g.slug)}`);
    lines.push(`    display_name: ${yamlEscape(g.display_name)}`);
    lines.push(`    location: ${yamlEscape(g.location)}`);
    lines.push(`    updated_at: ${yamlEscape(g.updated_at)}`);
  }
  return lines.join('\n') + '\n';
};

const stub = () => ({
  generated_at: new Date().toISOString(),
  tours: [],
  guides: [],
});

const fileExists = async (p) => {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
};

(async () => {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
  let payload;
  try {
    const res = await fetch(API_URL, { signal: ctrl.signal });
    if (!res.ok) throw new Error(`http ${res.status}`);
    payload = await res.json();
    if (!payload || !Array.isArray(payload.tours) || !Array.isArray(payload.guides)) {
      throw new Error('malformed payload');
    }
  } catch (err) {
    clearTimeout(timer);
    const msg = (err && err.message) || String(err);
    if (await fileExists(OUT)) {
      console.warn(
        `[prefetch-discovery] API unreachable (${msg}); keeping existing ${OUT}`
      );
      process.exit(0);
    }
    console.warn(
      `[prefetch-discovery] API unreachable (${msg}); writing empty stub to ${OUT}`
    );
    await mkdir(dirname(OUT), { recursive: true });
    await writeFile(OUT, renderYaml(stub()), 'utf8');
    process.exit(0);
  }
  clearTimeout(timer);
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, renderYaml(payload), 'utf8');
  console.log(
    `[prefetch-discovery] wrote ${OUT} (${payload.tours.length} tours, ${payload.guides.length} guides)`
  );
})();
